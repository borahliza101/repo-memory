"""Generate a decision log from a repo's commit memory."""

import argparse
import os
import re
from collections import defaultdict
from datetime import datetime
from zoneinfo import ZoneInfo

from ask import LLM_MODEL, get_groq_client, open_collection
from config import decisions_path, get_repo

BATCH_SIZE = 40  # commits per model call
IST = ZoneInfo("Asia/Kolkata")

# Words that don't count as extra detail when we compare a why against a title.
STOPWORDS = {
    "a", "an", "the", "and", "or", "for", "to", "of", "in", "on", "with", "that",
    "this", "so", "it", "is", "was", "be", "by", "from", "as", "at", "into", "then",
    "than", "their", "its", "all", "not", "no", "new", "when", "while",
}

EXTRACT_PROMPT = (
    "You read commit summaries from a software project and extract real decisions. "
    "A decision is a design change, support added or dropped, a behaviour change, "
    "or a fix that explains a reason. "
    "Skip version bumps, release tags, dependency bumps, typo fixes, formatting "
    "and pure docs edits. "
    "Use only the words in the commit text: never guess a reason that is not there. "
    "The why must add detail beyond the title (the motivation, the bug being fixed, "
    "or the behaviour that improves); if the commit states no reason, write "
    '"no reason given in the commit". '
    "Reply with one decision per line, in exactly this format and nothing else:\n"
    "<short sha> | <YYYY-MM-DD> | <one-line title> | <why>\n"
    "If a commit is not a decision, leave it out. If there are none, reply with nothing."
)


def load_summaries(repo):
    """Every commit summary (message + changed files) from the memory, oldest first."""
    collection = open_collection(repo)
    rows = collection.get(include=["documents", "metadatas"])
    summaries = [
        {"sha": metadata["sha"], "date": metadata["date"], "text": document}
        for chunk_id, document, metadata in zip(rows["ids"], rows["documents"], rows["metadatas"])
        if chunk_id.endswith("-summary")
    ]
    summaries.sort(key=lambda summary: summary["date"])
    return summaries


def parse_decision(line):
    """Turn '<sha> | <date> | <title> | <why>' into a dict, or None if malformed."""
    parts = [part.strip() for part in line.strip().lstrip("-*• ").split("|")]
    if len(parts) != 4:
        return None
    sha, date, title, why = parts
    sha = sha.strip("[]")
    if len(sha) != 7 or not title or not why:
        return None
    if not (len(date) == 10 and date[4] == "-" and date[7] == "-"):
        return None
    return {"sha": sha, "date": date, "title": title, "why": why}


def adds_detail(why, title):
    """True if the why says something the title doesn't already say."""
    title_words = set(re.findall(r"[a-z0-9_]+", title.lower()))
    why_words = set(re.findall(r"[a-z0-9_]+", why.lower()))
    extra = {word for word in why_words - title_words if word not in STOPWORDS}
    return bool(extra)


def extract_decisions(summaries):
    """Ask the model, in batches, which commits record real decisions."""
    client = get_groq_client()
    decisions = []
    for start in range(0, len(summaries), BATCH_SIZE):
        batch = summaries[start : start + BATCH_SIZE]
        commits = "\n\n".join(summary["text"] for summary in batch)
        response = client.chat.completions.create(
            model=LLM_MODEL,
            messages=[
                {"role": "system", "content": EXTRACT_PROMPT},
                {"role": "user", "content": f"Commits:\n\n{commits}"},
            ],
            temperature=0,
        )
        print(f"Batch {start // BATCH_SIZE + 1}: {len(batch)} commits")
        for line in response.choices[0].message.content.splitlines():
            decision = parse_decision(line)
            if decision:
                decisions.append(decision)
    return decisions


def render_log(repo, decisions, commit_count):
    """Markdown grouped by month, newest first."""
    today = datetime.now(IST).date().isoformat()
    lines = [
        f"# Decision log — {repo}",
        "",
        f"Auto-generated by Repo Memory from {commit_count} commits on {today}.",
        "",
    ]

    if not decisions:
        lines.append("No clear decisions were found in these commits.")
        return "\n".join(lines) + "\n"

    by_month = defaultdict(list)
    for decision in decisions:
        by_month[decision["date"][:7]].append(decision)

    for month in sorted(by_month, reverse=True):
        label = datetime.strptime(month, "%Y-%m").strftime("%B %Y")
        lines.append(f"## {label}")
        lines.append("")
        for decision in sorted(by_month[month], key=lambda item: item["sort"], reverse=True):
            lines.append(
                f"- **{decision['title']}** — {decision['why']} "
                f"([{decision['sha']}], {decision['date']})"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def generate(repo):
    """Build the decision log for one repo and save it. Returns (path, count)."""
    summaries = load_summaries(repo)
    if not summaries:
        print(f"No commits in memory for {repo}. Run build_memory.py first.")
        return None, 0

    decisions = extract_decisions(summaries)

    # Trust the stored commit date, not the model's: it is the real timestamp.
    date_by_sha = {summary["sha"][:7]: summary["date"] for summary in summaries}
    for decision in decisions:
        stored_date = date_by_sha.get(decision["sha"])
        if stored_date:
            decision["date"] = stored_date[:10]
        decision["sort"] = stored_date or decision["date"]
        # A "why" that only repeats the title is not a reason: say so instead.
        if not adds_detail(decision["why"], decision["title"]):
            decision["why"] = "no reason given in the commit"
    decisions.sort(key=lambda item: item["sort"], reverse=True)

    markdown = render_log(repo, decisions, len(summaries))

    path = decisions_path(repo)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(markdown)
    return path, len(decisions)


def main():
    parser = argparse.ArgumentParser(description="Write a decision log from the commit memory.")
    parser.add_argument("--repo", help="owner/name (default: REPO from .env, else psf/requests)")
    args = parser.parse_args()
    repo = get_repo(args.repo)

    path, count = generate(repo)
    if path:
        print(f"Wrote {count} decisions to {path}")


if __name__ == "__main__":
    main()